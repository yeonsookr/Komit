-- R-ACC-09: SSAFY 회원·입출금 계좌 발급은 에스크로가 실행한다.
-- R-PAY-10: 발급 직후 회원 계좌에 데모 자금을 한 번 입금한다.
-- 발급된 userKey, 은행코드, 계좌번호는 Komit이 보관한다. 에스크로는
-- 재요청의 중복 입금을 막는 데 필요한 업무·거래 식별자만 기록한다.

CREATE TABLE member_account_provisions (
    id                     BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    service_client_id      BIGINT       NOT NULL,
    user_id                VARCHAR(40)  NOT NULL,
    account_type_unique_no VARCHAR(20)  NOT NULL,
    idempotency_key        VARCHAR(255) NOT NULL,
    seed_amount            BIGINT       NOT NULL,
    seed_status            VARCHAR(12)  NOT NULL DEFAULT 'PENDING',
    seed_request_reference VARCHAR(20),
    seed_transaction_no    VARCHAR(40),
    seeded_at              TIMESTAMP(6),
    created_at             TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_member_account_provisions PRIMARY KEY (id),
    CONSTRAINT ck_member_account_provisions_seed_amount CHECK (seed_amount > 0),
    CONSTRAINT ck_member_account_provisions_seed_status
        CHECK (seed_status IN ('PENDING', 'UNKNOWN', 'COMPLETED')),
    CONSTRAINT ck_member_account_provisions_seed_completion CHECK (
        (seed_status = 'COMPLETED' AND seed_transaction_no IS NOT NULL AND seeded_at IS NOT NULL)
        OR (seed_status <> 'COMPLETED' AND seeded_at IS NULL)
    )
);

COMMENT ON TABLE member_account_provisions IS 'SSAFY 회원·계좌 발급과 1회 데모 입금의 중복 방지 기록. userKey와 계좌번호는 저장하지 않고, 입금액은 계약 예치 원장에 포함하지 않음 (R-ACC-09, R-PAY-10)';
COMMENT ON COLUMN member_account_provisions.id IS '발급 기록 식별자. 서버에서 생성';
COMMENT ON COLUMN member_account_provisions.service_client_id IS '발급을 요청한 이용 서비스 FK';
COMMENT ON COLUMN member_account_provisions.user_id IS 'SSAFY 회원 등록에 사용한 이메일 형식 userId. 중복 발급 방지에 사용';
COMMENT ON COLUMN member_account_provisions.account_type_unique_no IS '발급에 사용한 에스크로 설정의 SSAFY 입출금 상품 고유번호 (R-ACC-10)';
COMMENT ON COLUMN member_account_provisions.idempotency_key IS '같은 발급 업무의 재요청에서 유지하는 멱등키';
COMMENT ON COLUMN member_account_provisions.seed_amount IS '회원 계좌에 한 번 입금한 데모 자금. R-PAY-10의 금액을 에스크로 설정에서 공급';
COMMENT ON COLUMN member_account_provisions.seed_status IS '데모 입금 상태. 결과 불명이면 UNKNOWN으로 두고 조회로 해소하며 재입금하지 않음';
COMMENT ON COLUMN member_account_provisions.seed_request_reference IS '입금 API 호출 전에 기록할 20자리 기관거래고유번호';
COMMENT ON COLUMN member_account_provisions.seed_transaction_no IS '입금 API 응답의 transactionUniqueNo를 문자열로 정규화한 값';
COMMENT ON COLUMN member_account_provisions.seeded_at IS '데모 입금 성공이 확인된 시각';
COMMENT ON COLUMN member_account_provisions.created_at IS '회원 발급과 데모 입금 업무 기록을 시작한 시각';

ALTER TABLE member_account_provisions
    ADD CONSTRAINT fk_member_account_provisions_service_client
    FOREIGN KEY (service_client_id) REFERENCES service_clients (id);

-- 같은 이용 서비스의 같은 userId는 하나의 SSAFY 계좌 발급 업무로 취급한다.
ALTER TABLE member_account_provisions
    ADD CONSTRAINT uq_member_account_provisions_service_user
    UNIQUE (service_client_id, user_id);

