-- R-ACC-09: SSAFY 회원·입출금 계좌 발급은 에스크로가 실행한다.
-- 발급된 userKey, 은행코드, 계좌번호는 Komit이 보관한다. 데모에서는 정상적인
-- 발급 요청의 성공을 전제로 하며, 에스크로는 중복 발급 방지용 식별자만 기록한다.

CREATE TABLE member_account_provisions (
    id                     BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    service_client_id      BIGINT       NOT NULL,
    user_id                VARCHAR(40)  NOT NULL,
    account_type_unique_no VARCHAR(20)  NOT NULL,
    idempotency_key        VARCHAR(255) NOT NULL,
    created_at             TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_member_account_provisions PRIMARY KEY (id)
);

COMMENT ON TABLE member_account_provisions IS '회원가입 시 SSAFY 회원·계좌 발급의 중복 방지 기록. 성공한 발급만 기록하고 userKey와 계좌번호는 저장하지 않음 (R-ACC-09)';
COMMENT ON COLUMN member_account_provisions.id IS '발급 기록 식별자. 서버에서 생성';
COMMENT ON COLUMN member_account_provisions.service_client_id IS '발급을 요청한 이용 서비스 FK';
COMMENT ON COLUMN member_account_provisions.user_id IS 'SSAFY 회원 등록에 사용한 이메일 형식 userId. 중복 발급 방지에 사용';
COMMENT ON COLUMN member_account_provisions.account_type_unique_no IS '발급에 사용한 에스크로 설정의 SSAFY 입출금 상품 고유번호 (R-ACC-10)';
COMMENT ON COLUMN member_account_provisions.idempotency_key IS '같은 발급 업무의 재요청에서 유지하는 멱등키';
COMMENT ON COLUMN member_account_provisions.created_at IS 'SSAFY 사용자와 계좌가 모두 발급된 시각';

ALTER TABLE member_account_provisions
    ADD CONSTRAINT fk_member_account_provisions_service_client
    FOREIGN KEY (service_client_id) REFERENCES service_clients (id);

-- 같은 이용 서비스의 같은 userId는 하나의 SSAFY 계좌 발급 업무로 취급한다.
ALTER TABLE member_account_provisions
    ADD CONSTRAINT uq_member_account_provisions_service_user
    UNIQUE (service_client_id, user_id);

-- 같은 멱등키를 다른 userId로 재사용하면 기존 요청과 충돌한다.
ALTER TABLE member_account_provisions
    ADD CONSTRAINT uq_member_account_provisions_service_idempotency
    UNIQUE (service_client_id, idempotency_key);
