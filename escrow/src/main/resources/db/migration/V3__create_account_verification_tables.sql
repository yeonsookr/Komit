-- 계좌 확인과 금융망 신원(userKey) 보관. proposal.md 7절 "계좌 확인 / 외부 금융 연동 = Escrow" 기준.
-- Escrow가 금융망을 호출하는 유일한 서비스이므로 userKey를 여기 둔다.
-- userKey와 계좌번호는 호출 시 원문이 필요하므로 해시가 아니라 암호화(봉투 형식)로 보관한다.

-- 금융망 신원. Komit 사용자 한 명 = party 한 건. 계좌를 바꿔도(R-ACC-04) party와 userKey는 유지된다.
CREATE TABLE financial_parties (
    id                 BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    service_client_id  BIGINT       NOT NULL,
    external_party_ref VARCHAR(100) NOT NULL,
    user_key_encrypted TEXT         NOT NULL,
    status             VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',
    created_at         TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at         TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_financial_parties PRIMARY KEY (id)
);

COMMENT ON TABLE  financial_parties IS '금융망 신원. Komit 사용자와 금융망 userKey를 잇는다';
COMMENT ON COLUMN financial_parties.id IS 'party 식별자. 서버에서 생성';
COMMENT ON COLUMN financial_parties.service_client_id IS '이용 서비스 FK. party는 이용 서비스 범위에서 유일';
COMMENT ON COLUMN financial_parties.external_party_ref IS 'Komit이 넘기는 불투명 사용자 참조. 요청에 userKey 대신 이 값을 싣는다';
COMMENT ON COLUMN financial_parties.user_key_encrypted IS '금융망 userKey 암호문. 키 버전, nonce, 인증 태그를 포함한 암호화 봉투. 해시 아님';
COMMENT ON COLUMN financial_parties.status IS 'ACTIVE / WITHDRAWN. 탈퇴 데이터 보관 기간은 R-ACC-06';
COMMENT ON COLUMN financial_parties.created_at IS '생성 일시';
COMMENT ON COLUMN financial_parties.updated_at IS '수정 일시. 서버가 갱신';

-- 같은 이용 서비스가 같은 사용자 참조로 party를 두 번 만들 수 없다.
ALTER TABLE financial_parties
    ADD CONSTRAINT uq_financial_parties_service_client_ref
    UNIQUE (service_client_id, external_party_ref);

ALTER TABLE financial_parties
    ADD CONSTRAINT fk_financial_parties_service_client
    FOREIGN KEY (service_client_id) REFERENCES service_clients (id);


-- 등록·확인이 끝난 계좌. R-ACC-04에 따라 party당 유효 계좌는 1개만 유지한다.
-- 예치 출금(의뢰인), 지급/환불 수취(개발자·의뢰인)를 같은 모델로 다루고 방향만 다르게 쓴다.
CREATE TABLE registered_accounts (
    id                  BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    party_id            BIGINT       NOT NULL,
    bank_code           VARCHAR(10)  NOT NULL,
    account_no_encrypted TEXT        NOT NULL,
    holder_name         VARCHAR(100) NOT NULL,
    status              VARCHAR(20)  NOT NULL DEFAULT 'VERIFIED',
    verified_at         TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at          TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_registered_accounts PRIMARY KEY (id)
);

COMMENT ON TABLE  registered_accounts IS '1원 인증을 통과해 등록된 본인 명의 계좌. R-ACC-01, R-ACC-04';
COMMENT ON COLUMN registered_accounts.id IS '등록 계좌 식별자. 서버에서 생성';
COMMENT ON COLUMN registered_accounts.party_id IS 'financial_parties FK';
COMMENT ON COLUMN registered_accounts.bank_code IS '은행코드';
COMMENT ON COLUMN registered_accounts.account_no_encrypted IS '계좌번호 암호문. 봉투 형식. 로그 출력 금지 (R-LEG-02)';
COMMENT ON COLUMN registered_accounts.holder_name IS '금융망으로 확인한 예금주명';
COMMENT ON COLUMN registered_accounts.status IS 'VERIFIED / REPLACED. 새 계좌 확인 시 기존 건은 REPLACED (R-ACC-04)';
COMMENT ON COLUMN registered_accounts.verified_at IS '1원 인증 통과 시각';
COMMENT ON COLUMN registered_accounts.created_at IS '생성 일시';
COMMENT ON COLUMN registered_accounts.updated_at IS '수정 일시. 서버가 갱신';

ALTER TABLE registered_accounts
    ADD CONSTRAINT fk_registered_accounts_party
    FOREIGN KEY (party_id) REFERENCES financial_parties (id);

-- R-ACC-04: party당 유효(VERIFIED) 계좌는 최대 1개. 대체된 건(REPLACED)은 이력으로 남긴다.
CREATE UNIQUE INDEX uq_registered_accounts_verified_per_party
    ON registered_accounts (party_id)
    WHERE status = 'VERIFIED';


-- 1원 인증 시도. R-ACC-02(4자리 / 유효 시간), R-ACC-03(반복 실패 시 취소 후 재시작).
-- 금융망 accountAuth: openAccountAuth로 인증코드 송금, checkAuthCode로 검증.
CREATE TABLE account_verifications (
    id                   BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    party_id             BIGINT       NOT NULL,
    bank_code            VARCHAR(10)  NOT NULL,
    account_no_encrypted TEXT         NOT NULL,
    holder_name          VARCHAR(100),
    auth_text            VARCHAR(20)  NOT NULL,
    transaction_unique_no VARCHAR(100),
    status               VARCHAR(20)  NOT NULL DEFAULT 'REQUESTED',
    attempt_count        INT          NOT NULL DEFAULT 0,
    expires_at           TIMESTAMP(6) NOT NULL,
    verified_at          TIMESTAMP(6),
    resulting_account_id BIGINT,
    created_at           TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at           TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_account_verifications PRIMARY KEY (id)
);

COMMENT ON TABLE  account_verifications IS '1원 인증 시도. 성공 시 registered_accounts를 만든다';
COMMENT ON COLUMN account_verifications.id IS '인증 시도 식별자. 서버에서 생성';
COMMENT ON COLUMN account_verifications.party_id IS 'financial_parties FK';
COMMENT ON COLUMN account_verifications.bank_code IS '인증 대상 계좌의 은행코드';
COMMENT ON COLUMN account_verifications.account_no_encrypted IS '인증 대상 계좌번호 암호문. 봉투 형식. 로그 출력 금지';
COMMENT ON COLUMN account_verifications.holder_name IS '확인된 예금주명. 검증 전 NULL';
COMMENT ON COLUMN account_verifications.auth_text IS '입금자명에 표기할 인증 문구. 요청 시점 service_clients.one_won_auth_message 스냅샷';
COMMENT ON COLUMN account_verifications.transaction_unique_no IS 'openAccountAuth 응답의 거래 고유번호. 인증 송금 추적용';
COMMENT ON COLUMN account_verifications.status IS 'REQUESTED / VERIFIED / FAILED / EXPIRED / CANCELLED';
COMMENT ON COLUMN account_verifications.attempt_count IS '인증코드 입력 실패 누적. 임계값 초과 시 취소 (R-ACC-03). 임계값은 미확정';
COMMENT ON COLUMN account_verifications.expires_at IS '인증 만료 시각. 유효 시간은 R-ACC-02, 코드가 아니라 애플리케이션이 계산해 채운다';
COMMENT ON COLUMN account_verifications.verified_at IS '검증 성공 시각. 미검증 NULL';
COMMENT ON COLUMN account_verifications.resulting_account_id IS '성공으로 생성한 registered_accounts FK. 감사 추적용. 실패 NULL';
COMMENT ON COLUMN account_verifications.created_at IS '생성 일시';
COMMENT ON COLUMN account_verifications.updated_at IS '수정 일시. 서버가 갱신';

ALTER TABLE account_verifications
    ADD CONSTRAINT fk_account_verifications_party
    FOREIGN KEY (party_id) REFERENCES financial_parties (id);

ALTER TABLE account_verifications
    ADD CONSTRAINT fk_account_verifications_resulting_account
    FOREIGN KEY (resulting_account_id) REFERENCES registered_accounts (id);

-- party별 진행 중 인증 조회.
CREATE INDEX idx_account_verifications_party_status
    ON account_verifications (party_id, status);

-- 만료 처리 대상을 오래된 것부터 스캔.
CREATE INDEX idx_account_verifications_status_expires_at
    ON account_verifications (status, expires_at);
