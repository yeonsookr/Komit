CREATE TABLE reconciliation_snapshots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    as_of TIMESTAMPTZ(6) NOT NULL,
    ledger_total NUMERIC(19, 0) NOT NULL,
    bank_balance NUMERIC(19, 0) NOT NULL,
    difference_amount NUMERIC(19, 0) NOT NULL,
    result VARCHAR(20) NOT NULL,
    escrow_count INT NOT NULL,
    created_at TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_reconciliation_snapshots_amounts CHECK (
        ledger_total >= 0 AND bank_balance >= 0
        AND difference_amount = bank_balance - ledger_total
    ),
    CONSTRAINT ck_reconciliation_snapshots_result CHECK (
        (difference_amount = 0 AND result = 'MATCHED')
        OR (difference_amount <> 0 AND result = 'BANK_MISMATCH')
    ),
    CONSTRAINT ck_reconciliation_snapshots_count CHECK (escrow_count >= 0)
);

CREATE INDEX idx_reconciliation_snapshots_as_of
    ON reconciliation_snapshots (as_of DESC);

COMMENT ON TABLE reconciliation_snapshots IS '보관계좌 대사 스냅샷 | 실제 금융망 잔액과 완료 원장을 같은 조회 시점에 비교한 운영 이력 (R-PAY-13)';
COMMENT ON COLUMN reconciliation_snapshots.as_of IS '대사 기준 시각 | 금융망 잔액 조회가 완료된 실제 시각';
