CREATE TABLE financial_operation_attempts (
    id                    BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    transaction_id        BIGINT       NOT NULL,
    step                  VARCHAR(30)  NOT NULL,
    attempt_no            INT          NOT NULL,
    request_reference     VARCHAR(100) NOT NULL,
    status                VARCHAR(20)  NOT NULL DEFAULT 'REQUESTED',
    external_transaction_id VARCHAR(100),
    response_code         VARCHAR(50),
    requested_at          TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    responded_at          TIMESTAMP(6),
    CONSTRAINT pk_financial_operation_attempts PRIMARY KEY (id)
);

COMMENT ON TABLE  financial_operation_attempts IS '외부 금융 호출 시도. 논리 거래 1건이 여러 호출로 나뉘는 것을 기록';
COMMENT ON COLUMN financial_operation_attempts.id IS '외부 금융 호출 시도 식별자. 서버에서 생성';
COMMENT ON COLUMN financial_operation_attempts.transaction_id IS '논리 금융 거래 FK';
COMMENT ON COLUMN financial_operation_attempts.step IS 'VA_CREATE / DEPOSIT_TRANSFER / DEPOSIT_VERIFY / VA_SETTLE / VA_CLOSE / HOLDER_VERIFY / PAYOUT_TRANSFER / REFUND_TRANSFER / RESULT_QUERY';
COMMENT ON COLUMN financial_operation_attempts.attempt_no IS '같은 논리 거래와 단계 안에서 1부터 증가하는 호출 시도 번호';
COMMENT ON COLUMN financial_operation_attempts.request_reference IS '외부 호출 전에 영속 저장하는 요청 식별자. 기관 요구 형식 사용. 로컬 ID만으로 외부 조회 가능하다고 가정하지 않음';
COMMENT ON COLUMN financial_operation_attempts.status IS 'REQUESTED / SUCCEEDED / FAILED / UNKNOWN. 미확정 호출은 재송금 전에 조회 또는 운영자 확인';
COMMENT ON COLUMN financial_operation_attempts.external_transaction_id IS '해당 단계의 외부 결과 식별자. 응답 유실 또는 미제공 시 NULL';
COMMENT ON COLUMN financial_operation_attempts.response_code IS '금융기관 응답 코드. 정상 응답을 받지 못했으면 NULL';
COMMENT ON COLUMN financial_operation_attempts.requested_at IS '외부 호출 준비 기록 시각. 실제 전송 여부를 증명하지 않음';
COMMENT ON COLUMN financial_operation_attempts.responded_at IS '응답 수신 시각. 응답 유실이면 NULL; 후속 조회는 별도 시도로 기록';
