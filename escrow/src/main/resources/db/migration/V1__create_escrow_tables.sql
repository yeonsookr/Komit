-- 에스크로 기본 테이블. ERD 기준이며 제약(UNIQUE/FK/인덱스)은 V2에서 추가한다.
-- 시각 컬럼은 timestamp(6)으로 두고 UTC 저장을 전제한다. (application.yml: hibernate.jdbc.time_zone=UTC)
-- 금액은 원 단위 정수이므로 numeric(19, 0)을 쓴다.

CREATE TABLE service_clients (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    name        VARCHAR(100) NOT NULL,
    api_key_hash VARCHAR(255) NOT NULL,
    status      VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',
    one_won_auth_message VARCHAR(100),
    created_at  TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_service_clients PRIMARY KEY (id)
);

COMMENT ON TABLE  service_clients IS '에스크로를 호출하는 이용 서비스';
COMMENT ON COLUMN service_clients.id IS '이용 서비스 식별자. 서버에서 생성';
COMMENT ON COLUMN service_clients.name IS '이용 서비스명';
COMMENT ON COLUMN service_clients.api_key_hash IS '충분히 무작위인 서비스 인증키의 SHA-256 등 해시. 원문 저장 금지';
COMMENT ON COLUMN service_clients.status IS 'ACTIVE / SUSPENDED / CLOSED';
COMMENT ON COLUMN service_clients.one_won_auth_message IS '1원 인증 시 입금자명에 표시할 인증 문구';
COMMENT ON COLUMN service_clients.created_at IS '생성 일시';
COMMENT ON COLUMN service_clients.updated_at IS '수정 일시. 서버가 갱신';


CREATE TABLE escrows (
    id                   BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    service_client_id    BIGINT       NOT NULL,
    external_contract_id VARCHAR(100) NOT NULL,
    contract_type        VARCHAR(30)  NOT NULL,
    expected_amount      NUMERIC(19, 0) NOT NULL,
    status               VARCHAR(30)  NOT NULL DEFAULT 'CREATED',
    closed_at            TIMESTAMP(6),
    cancelled_at         TIMESTAMP(6),
    hold_status          VARCHAR(20)  NOT NULL DEFAULT 'NONE',
    external_report_id   VARCHAR(100),
    held_at              TIMESTAMP(6),
    released_at          TIMESTAMP(6),
    created_at           TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at           TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_escrows PRIMARY KEY (id)
);

COMMENT ON TABLE  escrows IS '계약 단위 예치. 계약 1건에 예치 1건';
COMMENT ON COLUMN escrows.id IS '에스크로 식별자. 서버에서 생성';
COMMENT ON COLUMN escrows.service_client_id IS '이용 서비스 FK';
COMMENT ON COLUMN escrows.external_contract_id IS '이용 서비스의 안정적인 외부 계약 식별값. 새 계약은 새 값 사용';
COMMENT ON COLUMN escrows.contract_type IS '이용 서비스가 정의한 계약 구분. 외부 계약 식별 범위에 포함';
COMMENT ON COLUMN escrows.expected_amount IS '계약 전액 예치 목표 금액. 생성 후 불변. 특약 및 추가 예치 없음';
COMMENT ON COLUMN escrows.status IS 'CREATED / DEPOSIT_PENDING / ACTIVE / COMPLETED / REFUNDED / CANCELLED';
COMMENT ON COLUMN escrows.closed_at IS '계약 최종 정산의 지급과 환불이 모두 완료되고 잔액이 0인 종료 시각. 예치 전 취소도 종료. 한쪽 처리 중이면 NULL';
COMMENT ON COLUMN escrows.cancelled_at IS '예치 전 취소 시각. 처리 중 또는 결과 불명 예치가 있으면 취소 금지';
COMMENT ON COLUMN escrows.hold_status IS 'NONE / HELD / RELEASED. HELD 상태에서는 지급과 일반 환불 실행 차단';
COMMENT ON COLUMN escrows.external_report_id IS '현재 또는 가장 최근 동결의 Komit 신고 식별값. 활성 신고는 최대 1개';
COMMENT ON COLUMN escrows.held_at IS '현재 또는 가장 최근 신고로 동결한 시각';
COMMENT ON COLUMN escrows.released_at IS '현재 또는 가장 최근 동결을 해제한 시각. 동결 중 NULL';
COMMENT ON COLUMN escrows.created_at IS '생성 일시';
COMMENT ON COLUMN escrows.updated_at IS '수정 일시. 서버가 갱신';


CREATE TABLE escrow_transactions (
    id                    BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    escrow_id             BIGINT       NOT NULL,
    transaction_type      VARCHAR(20)  NOT NULL,
    amount                NUMERIC(19, 0) NOT NULL,
    status                VARCHAR(20)  NOT NULL DEFAULT 'PENDING',
    external_reference_id VARCHAR(200) NOT NULL,
    idempotency_key       VARCHAR(100) NOT NULL,
    request_fingerprint   VARCHAR(64)  NOT NULL,
    deposit_step          VARCHAR(30),
    virtual_account_id    VARCHAR(100),
    virtual_account_no    VARCHAR(100),
    deposit_verification_status VARCHAR(20),
    verified_deposit_amount     NUMERIC(19, 0),
    depositor_name_matched      BOOLEAN,
    source_bank_code            VARCHAR(10),
    source_account_encrypted    TEXT,
    recipient_bank_code         VARCHAR(10),
    recipient_account_encrypted TEXT,
    recipient_name              VARCHAR(100),
    financial_transaction_id    VARCHAR(100),
    virtual_account_closed_at   TIMESTAMP(6),
    failure_code                VARCHAR(30),
    created_at            TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at            TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at          TIMESTAMP(6),
    CONSTRAINT pk_escrow_transactions PRIMARY KEY (id)
);

COMMENT ON TABLE  escrow_transactions IS '업무 단위 자금 거래. 외부 호출 단위 기록은 financial_operation_attempts에 둔다';
COMMENT ON COLUMN escrow_transactions.id IS '논리 금융 거래 식별자. 복식부기 전표가 아닌 업무 거래 기록';
COMMENT ON COLUMN escrow_transactions.escrow_id IS '에스크로 FK';
COMMENT ON COLUMN escrow_transactions.transaction_type IS 'DEPOSIT 예치 / RELEASE 계약 최종 지급 / REFUND 계약 잔액 환불. 마일스톤 개별 승인만으로 RELEASE 생성 금지';
COMMENT ON COLUMN escrow_transactions.amount IS '원 단위 양수. RELEASE는 정상 완료 전액 또는 중도 종료 확정 승인 마일스톤 합계. REFUND는 나머지 금액. 생성 후 불변';
COMMENT ON COLUMN escrow_transactions.status IS 'PENDING / PROCESSING / UNKNOWN / COMPLETED / FAILED. UNKNOWN은 실패가 아님';
COMMENT ON COLUMN escrow_transactions.external_reference_id IS '예치는 INITIAL. 계약 최종 정산 지급과 환불은 같은 SETTLEMENT:정산ID 사용, 거래 유형으로 구분. 재시도도 동일 값. 마일스톤 ID 사용 금지';
COMMENT ON COLUMN escrow_transactions.idempotency_key IS '동일 요청 재전송 시 유지. 같은 업무의 새 키 요청도 새 거래를 생성하지 않음';
COMMENT ON COLUMN escrow_transactions.request_fingerprint IS '정규화된 금액, 대상, 권한 범위 등 요청의 SHA-256 hex. 같은 키 또는 업무 참조의 다른 내용은 충돌';
COMMENT ON COLUMN escrow_transactions.deposit_step IS 'DEPOSIT 전용: VA_CREATING / VA_CREATED / TRANSFER_SENDING / TRANSFERRED / VERIFIED / SETTLED / VA_CLOSED';
COMMENT ON COLUMN escrow_transactions.virtual_account_id IS '금융기관이 반환한 가상계좌 식별자. 발급 전 NULL';
COMMENT ON COLUMN escrow_transactions.virtual_account_no IS '가상계좌 번호. 표시 목적 외 접근 차단, 로그 출력 금지. 암호문 컬럼은 아님';
